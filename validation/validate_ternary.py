"""Validate SWEQ against measured NH3-H2S-CO2-H2O data (no parameter was fitted to these data).
Sources (all compiled in IUPAC Solubility Data Series vol. 32, Fogg & Young 1988):
  Wilson, Gillespie & Owens (1985) GPA - mole %, partial pressures in bar (366 K; 422 K is extrapolation)
  Badger & Silver (1938) - 293 K, mol/dm3, mmHg
  van Krevelen, Hoftijzer & Huntjens (1949) - 293-333 K, mol/dm3, p(H2S) only
mol/dm3 are converted to molality assuming a solution density of 1.0 kg/L (not given in the sources).
Partial pressures below 0.5 mmHg (0.00067 bar) are excluded.
Run: python validation/validate_ternary.py  -> prints and writes validation/RESULTS_TERNARY.md"""
import csv, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'dwsim'))
import SWEQ_Solver as S
PSI_TO_BAR = 0.0689476
MMHG = 1.01325 / 760.0
MW = S.CONST['MW']
GASES = ('NH3', 'CO2', 'H2S')

def read(name):
    with open(os.path.join(HERE, 'data', name)) as f:
        return [{k: (float(v) if v != '' else None) for k, v in r.items()}
                for r in csv.DictReader(l for l in f if not l.startswith('#'))]

def from_molar(r):
    kw = 1.0 - sum(r['c_%s_molL' % k] * MW[k] for k in GASES) / 1000.0
    return {k: r['c_%s_molL' % k] / kw for k in GASES}

def points():
    """Yields (set_name, T, molalities, {gas: p_exp_bar or None})."""
    for r in read('wilson_gpa_1985.csv'):
        kw = r['x_H2O_pct'] * MW['H2O'] / 1000.0
        name = 'Wilson 1985, 366 K' if r['T_K'] < 400 else 'Wilson 1985, 422 K (extrapolation)'
        yield name, r['T_K'], {k: r['x_%s_pct' % k] / kw for k in GASES}, {k: r['p_%s_bar' % k] for k in GASES}
    for r in read('badger_silver_1938.csv'):
        yield ('Badger & Silver 1938, 293 K', r['T_K'], from_molar(r),
               {k: (r['p_%s_mmHg' % k] * MMHG if r['p_%s_mmHg' % k] is not None else None) for k in GASES})
    for r in read('van_krevelen_1949.csv'):
        yield ('van Krevelen 1949, 293-333 K', r['T_K'], from_molar(r),
               {'NH3': None, 'CO2': None, 'H2S': r['p_H2S_mmHg'] * MMHG})

def evaluate():
    stats = {}
    for name, T, m, pexp in points():
        pp = S.calculate_equilibrium(T, {'NH3': m['NH3'], 'H2S': m['H2S'], 'CO2': m['CO2']})['pp']
        d = stats.setdefault(name, {g: [] for g in GASES})
        for g in GASES:
            if pexp[g] is not None and pexp[g] > 0.5 * MMHG:
                d[g].append(pp[g] * PSI_TO_BAR / pexp[g] - 1.0)
    return stats

def summary(stats):
    rows = []
    for name, d in stats.items():
        cells = []
        for g in GASES:
            xs = d[g]
            cells.append("%5.1f%% (bias %+5.1f%%, n=%d)" % (100*sum(abs(x) for x in xs)/len(xs), 100*sum(xs)/len(xs), len(xs)) if xs else "   -")
        rows.append("  %-36s p(NH3) %-28s p(CO2) %-28s p(H2S) %s" % (name, *cells))
    return "\n".join(rows)

if __name__ == '__main__':
    head = "SWEQ %s vs measured NH3-H2S-CO2-H2O data (independent test, no parameters fitted):" % S.__version__
    body = summary(evaluate())
    print(head); print(body)
    with open(os.path.join(HERE, 'RESULTS_TERNARY.md'), 'w') as f:
        f.write("# NH3-H2S-CO2-H2O validation\n\nGenerated by `validation/validate_ternary.py`. "
                "AAD = average absolute deviation. None of these data were used to fit parameters.\n\n```\n%s\n%s\n```\n" % (head, body))
