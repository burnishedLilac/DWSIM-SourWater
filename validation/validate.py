"""Validate SWEQ against published experimental NH3-H2S-H2O VLE data.

Data: IUPAC Solubility Data Series vol. 32 (Fogg & Young, 1988), as compiled
at https://srdata.nist.gov/solubility/IUPAC/SDS-32/  (see headers of each CSV).

Run:  python validation/validate.py      -> prints summary, writes validation/RESULTS.md
This script reports deviations; it does not fail on them (no fitting is done here).
"""
import csv, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'dwsim'))
import SWEQ_Solver as S

PSI_TO_BAR = 0.0689476
MMHG_TO_BAR = 1.01325 / 760.0
MW = S.CONST['MW']

def read(name):
    with open(os.path.join(HERE, 'data', name)) as f:
        return list(csv.DictReader(l for l in f if not l.startswith('#')))

def predict(T, m_nh3, m_h2s):
    r = S.calculate_equilibrium(T, {'NH3': m_nh3, 'H2S': m_h2s, 'CO2': 0.0})
    return {k: v * PSI_TO_BAR for k, v in r['pp'].items()}, r

def from_wt(w_h2s, w_nh3):
    kg_w = (100.0 - w_h2s - w_nh3) / 1000.0
    return w_nh3 / MW['NH3'] / kg_w, w_h2s / MW['H2S'] / kg_w

def from_molar(c_h2s, c_nh3, rho=1.0):
    # ASSUMPTION: solution density rho (kg/L) = 1.0; the source gives no density.
    kg_w = rho - (c_h2s * MW['H2S'] + c_nh3 * MW['NH3']) / 1000.0
    return c_nh3 / kg_w, c_h2s / kg_w

def dev(calc, exp):
    return 100.0 * (calc - exp) / exp

datasets = []

# Oratovskii et al. 1964 (wt%, bar)
pts = []
for r in read('oratovskii_1964.csv'):
    T = float(r['T_K']); mN, mS = from_wt(float(r['w_H2S_pct']), float(r['w_NH3_pct']))
    pp, res = predict(T, mN, mS)
    pts.append(dict(T=T, mN=mN, mS=mS, ph=res['ph'],
                    eS=float(r['p_H2S_bar']), cS=pp['H2S'], eN=float(r['p_NH3_bar']), cN=pp['NH3']))
datasets.append(("Oratovskii, Gamol'skii & Klimenko (1964)", "wt% converted exactly to molality", pts))

# Leyko 1959 (mol/dm3, mmHg)
pts = []
for r in read('leyko_1959.csv'):
    T = float(r['T_K']); mN, mS = from_molar(float(r['c_H2S_molL']), float(r['c_NH3_molL']))
    pp, res = predict(T, mN, mS)
    pts.append(dict(T=T, mN=mN, mS=mS, ph=res['ph'],
                    eS=float(r['p_H2S_mmHg'])*MMHG_TO_BAR, cS=pp['H2S'],
                    eN=float(r['p_NH3_mmHg'])*MMHG_TO_BAR, cN=pp['NH3'],
                    eW=float(r['p_H2O_mmHg'])*MMHG_TO_BAR, cW=pp['H2O']))
datasets.append(("Leyko (1959)", "mol/dm3 converted to molality assuming density 1.0 kg/L (not given in source)", pts))

def aad(xs): return sum(abs(x) for x in xs) / len(xs)
def bias(xs): return sum(xs) / len(xs)

out = ["# SWEQ validation against experimental data", "",
       "Generated by `validation/validate.py` with SWEQ v%s. Deviation = (calc − exp)/exp. "
       "AAD = average absolute deviation." % S.__version__, "",
       "Source of all data: IUPAC Solubility Data Series vol. 32 (Fogg & Young, 1988), "
       "https://srdata.nist.gov/solubility/IUPAC/SDS-32/SDS-32-pages_54.pdf", ""]
summary = []
for name, note, pts in datasets:
    dS = [dev(p['cS'], p['eS']) for p in pts]; dN = [dev(p['cN'], p['eN']) for p in pts]
    lo = [p for p in pts if p['mN'] <= 3.0]
    line = "%-42s n=%2d | p(H2S) AAD %5.1f%% bias %+6.1f%% | p(NH3) AAD %5.1f%% bias %+6.1f%%" % (
        name, len(pts), aad(dS), bias(dS), aad(dN), bias(dN))
    summary.append(line)
    out += ["## %s" % name, "", "_%s._" % note, "",
            "| Metric | p(H2S) | p(NH3) |", "|---|---|---|",
            "| AAD, all points (n=%d) | %.1f%% | %.1f%% |" % (len(pts), aad(dS), aad(dN)),
            "| Bias, all points | %+.1f%% | %+.1f%% |" % (bias(dS), bias(dN))]
    if lo:
        out.append("| AAD, m(NH3) ≤ 3 mol/kg (n=%d) | %.1f%% | %.1f%% |" % (
            len(lo), aad([dev(p['cS'], p['eS']) for p in lo]), aad([dev(p['cN'], p['eN']) for p in lo])))
    out += ["", "| T (K) | m NH3 | m H2S | pH calc | p(H2S) exp | p(H2S) calc | dev | p(NH3) exp | p(NH3) calc | dev |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for p in pts:
        out.append("| %.1f | %.2f | %.2f | %.2f | %.4f | %.4f | %+.0f%% | %.4f | %.4f | %+.0f%% |" % (
            p['T'], p['mN'], p['mS'], p['ph'], p['eS'], p['cS'], dev(p['cS'], p['eS']),
            p['eN'], p['cN'], dev(p['cN'], p['eN'])))
    out += ["", "Pressures in bar.", ""]

out += ["## Interpretation", "",
        "* At moderate concentration (NH3 ≲ 3 mol/kg) p(H2S) is reproduced reasonably; deviations grow "
        "with concentration: H2S is over-predicted and NH3 under-predicted.",
        "* This is the expected signature of the missing ion–molecule Pitzer parameters "
        "(NH3–NH4HS, H2S–NH4HS) and of the constant, uncited β0/β1 for NH4+/HS−.",
        "* Next step: regress those parameters (with temperature dependence) against these and other "
        "published data sets (e.g. Rumpf et al. 1999, Kurz et al. 1995), keeping a hold-out set.", ""]
open(os.path.join(HERE, 'RESULTS.md'), 'w').write("\n".join(out))
print("\n".join(summary)); print("\nWrote validation/RESULTS.md")
