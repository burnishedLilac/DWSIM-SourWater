"""Validate SWEQ against Kurz, Rumpf & Maurer (1995) NH3-CO2-H2O data (VLE points only).
Run: python validation/validate_co2.py
Partial pressures below 2 kPa (experimental uncertainty comparable to the value) are excluded."""
import csv, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'dwsim'))
import SWEQ_Solver as S
PSI_TO_KPA = 6.89476

def load():
    with open(os.path.join(HERE, 'data', 'kurz_1995.csv')) as f:
        rows = list(csv.DictReader(l for l in f if not l.startswith('#')))
    return [{k: float(v) for k, v in r.items() if v != ''} for r in rows if r['phases'] == '2']

def evaluate(rows=None, by_T=False):
    rows = rows or load()
    out = {}
    for r in rows:
        q = S.calculate_equilibrium(r['T_K'], {'NH3': r['m_NH3'], 'H2S': 0.0, 'CO2': r['m_CO2']})
        key = int(round(r['T_K'] / 10) * 10) if by_T else 'all'
        d = out.setdefault(key, {'NH3': [], 'CO2': [], 'P': []})
        if r['p_NH3_kPa'] > 2: d['NH3'].append(q['pp']['NH3'] * PSI_TO_KPA / r['p_NH3_kPa'] - 1)
        if r['p_CO2_kPa'] > 2: d['CO2'].append(q['pp']['CO2'] * PSI_TO_KPA / r['p_CO2_kPa'] - 1)
        d['P'].append(q['P_bubble'] / 1000.0 / r['p_total_kPa'] - 1)
    return out

def summary(out):
    s = []
    for k, d in sorted(out.items(), key=lambda kv: str(kv[0])):
        f = lambda xs: "%5.1f%% (bias %+5.1f%%, n=%d)" % (100*sum(abs(x) for x in xs)/len(xs), 100*sum(xs)/len(xs), len(xs))
        s.append("  %-4s p(NH3) %s | p(CO2) %s | p_total %s" % (k, f(d['NH3']), f(d['CO2']), f(d['P'])))
    return "\n".join(s)

if __name__ == '__main__':
    head = "SWEQ %s vs Kurz et al. 1995 (VLE points; 313/353 K used in fit, 333 K hold-out):" % S.__version__
    body = summary(evaluate(by_T=True)) + "\n" + summary(evaluate())
    print(head); print(body)
    with open(os.path.join(HERE, 'RESULTS_CO2.md'), 'w') as f:
        f.write("# NH3-CO2-H2O validation\n\nGenerated by `validation/validate_co2.py`. AAD = average absolute deviation; "
                "partial pressures <= 2 kPa excluded; three-phase (solid NH4HCO3) points excluded.\n\n```\n%s\n%s\n```\n" % (head, body))
